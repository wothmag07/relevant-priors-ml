"""Per-modality slice analysis on the public split.

For each modality of the *current* study, compute accuracy / precision / recall
/ F1 for both predictors. This surfaces where the classifier helps and where
the heuristic is already strong (or already broken).

Run: python -m eval.slice_analysis
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

# Windows default cp1252 stdout can't print unicode (Δ, ✓, etc). Reconfigure.
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

import numpy as np  # noqa: E402
from sklearn.model_selection import GroupKFold  # noqa: E402

from app.heuristic import predict_pair  # noqa: E402
from app.parser import parse_description  # noqa: E402
from eval.train_classifier import build_matrix, load_pairs, train_one  # noqa: E402

PUBLIC_JSON = ROOT / "relevant_priors_public.json"
OUT = ROOT / "docs" / "slice_analysis.md"


def oof_classifier_proba(X, y, groups, folds: int = 5):
    proba = np.zeros(len(y), dtype=np.float32)
    gkf = GroupKFold(n_splits=folds)
    for tr_idx, te_idx in gkf.split(X, y, groups):
        model = train_one(X[tr_idx], y[tr_idx])
        proba[te_idx] = model.predict(X[te_idx])
    return proba


def heur_predictions(rows):
    return np.array(
        [predict_pair(r["curr_desc"], r["prior_desc"]).predicted for r in rows],
        dtype=bool,
    )


def modality_of(desc: str) -> str:
    """Coarse modality bucket from the parser; 'unknown' if none detected."""
    tags = parse_description(desc)
    return tags.modality or "unknown"


def metrics(y_true: np.ndarray, y_pred: np.ndarray) -> dict[str, float]:
    tp = int(((y_true == 1) & (y_pred == 1)).sum())
    fp = int(((y_true == 0) & (y_pred == 1)).sum())
    tn = int(((y_true == 0) & (y_pred == 0)).sum())
    fn = int(((y_true == 1) & (y_pred == 0)).sum())
    n = tp + fp + tn + fn
    acc = (tp + tn) / n if n else 0.0
    prec = tp / (tp + fp) if (tp + fp) else float("nan")
    rec = tp / (tp + fn) if (tp + fn) else float("nan")
    f1 = 2 * prec * rec / (prec + rec) if (prec and rec and not np.isnan(prec) and not np.isnan(rec)) else float("nan")
    return {"n": n, "pos_rate": (tp + fn) / n if n else 0.0,
            "acc": acc, "prec": prec, "rec": rec, "f1": f1}


def fmt(x: float) -> str:
    return f"{x:.3f}" if not np.isnan(x) else "  —  "


def main() -> None:
    print(f"Loading {PUBLIC_JSON} ...")
    rows = load_pairs(PUBLIC_JSON)
    print(f"  rows: {len(rows)}")

    print("Building feature matrix ...")
    X, y, _ = build_matrix(rows)
    groups = np.array([f"{r['curr_desc']}||{r['prior_desc']}" for r in rows])

    print("Running 5-fold GroupKFold CV ...")
    proba = oof_classifier_proba(X, y, groups, folds=5)
    pred_clf = (proba >= 0.5).astype(bool)

    print("Running heuristic baseline ...")
    pred_heur = heur_predictions(rows)

    modalities = np.array([modality_of(r["curr_desc"]) for r in rows])

    lines = [
        "# Per-modality slice analysis",
        "",
        "Per-current-modality breakdown of heuristic vs LightGBM (5-fold OOF) on",
        "the public split. Generated by `python -m eval.slice_analysis`.",
        "",
        "| Curr modality | N | Pos rate | Heur acc | Heur F1 | CLF acc | CLF F1 | Δ F1 |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]

    # Sort by support, descending
    order = sorted(set(modalities.tolist()), key=lambda m: -int((modalities == m).sum()))
    for mod in order:
        mask = modalities == mod
        if mask.sum() < 50:
            continue  # skip tiny slices — noise dominates
        m_h = metrics(y[mask].astype(int), pred_heur[mask].astype(int))
        m_c = metrics(y[mask].astype(int), pred_clf[mask].astype(int))
        delta_f1 = m_c["f1"] - m_h["f1"]
        delta_str = f"{delta_f1:+.3f}" if not np.isnan(delta_f1) else "  —  "
        lines.append(
            f"| `{mod}` | {m_h['n']:,} | {m_h['pos_rate']:.3f} | "
            f"{fmt(m_h['acc'])} | {fmt(m_h['f1'])} | "
            f"{fmt(m_c['acc'])} | {fmt(m_c['f1'])} | "
            f"{delta_str} |"
        )

    # Also print as plain text to stdout
    text = "\n".join(lines) + "\n"
    print()
    print(text)

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"\nWrote {OUT}")


if __name__ == "__main__":
    main()
